const L = (
  id: string,
  title: string,
  emoji: string,
  grade: GradeLevel,
  questions: Lesson["questions"],
): Lesson => ({ id, title, emoji, grade, questions });

const Q = (
  prompt: string,
  options: string[],
  answerIndex: number,
  hint?: string,
  explanation?: string,
) => ({ prompt, options, answerIndex, hint, explanation });

const VF = (prompt: string, answerIndex: number, hint?: string, explanation?: string) => ({
  prompt,
  options: ["Verdadeiro", "Falso"],
  answerIndex,
  hint,
  explanation,
});

const O = (prompt: string, sequence: string[], hint?: string, explanation?: string) => ({
  prompt,
  kind: "order" as const,
  sequence,
  hint,
  explanation,
});

